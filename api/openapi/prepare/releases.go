package main

import (
	"fmt"
	"go/format"
	"regexp"
	"strings"

	"go.yaml.in/yaml/v3"
)

// releaseTag is a release tag as spec-releases.yaml records it: vX.Y.Z.
var releaseTag = regexp.MustCompile(`^v(\d+\.\d+\.\d+)$`)

// specReleasesGo turns spec-releases.yaml, the release each committed spec
// was copied from, into a Go source file for the generated package. The SDK
// derives its supported server versions, and the server-too-old diagnosis,
// from these constants.
func specReleasesGo(releasesYAML []byte) ([]byte, error) {
	var releases struct {
		Lakekeeper     string `yaml:"lakekeeper"`
		LakekeeperPlus string `yaml:"lakekeeper-plus"`
	}
	if err := yaml.Unmarshal(releasesYAML, &releases); err != nil {
		return nil, fmt.Errorf("parse spec releases: %w", err)
	}
	lk, err := releaseVersion("lakekeeper", releases.Lakekeeper)
	if err != nil {
		return nil, err
	}
	plus, err := releaseVersion("lakekeeper-plus", releases.LakekeeperPlus)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by prepare from api/openapi/spec-releases.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package managementv1\n\n")
	b.WriteString("// The releases the specs this package is generated from were copied from.\n")
	b.WriteString("const (\n")
	b.WriteString("\t// LakekeeperSpecRelease is the Lakekeeper release of the Lakekeeper spec.\n")
	fmt.Fprintf(&b, "\tLakekeeperSpecRelease = %q\n", lk)
	b.WriteString("\t// LakekeeperPlusSpecRelease is the Lakekeeper+ release of the Lakekeeper+ spec.\n")
	fmt.Fprintf(&b, "\tLakekeeperPlusSpecRelease = %q\n", plus)
	b.WriteString(")\n")
	return format.Source([]byte(b.String()))
}

// releaseVersion checks that tag is a vX.Y.Z release tag and returns X.Y.Z,
// the form a server reports its version in.
func releaseVersion(key, tag string) (string, error) {
	m := releaseTag.FindStringSubmatch(tag)
	if m == nil {
		return "", fmt.Errorf("spec releases: %s is %q, want a release tag vX.Y.Z", key, tag)
	}
	return m[1], nil
}
